# -*- coding: utf-8 -*-
"""i18n_merge —— 把 5.0 新增文案的片段文件合并进双语字典，并重生成 ``embed.js``（纯标准库）。

为什么需要这个工具（而不是直接改 zh.json）
------------------------------------------
5.0 的九块新界面由不同成员并行开发，如果每个人都直接改 ``web/i18n/zh.json`` 与
``web/i18n/en.json``，同一个文件会被反复覆盖。约定于是变成：

* 每个功能只写自己的片段：``web/i18n/parts/<feature>.zh.json`` / ``.en.json``；
* 由本工具一次性合并、校验并重生成 ``embed.js``（``file://`` 打开也要有字典）。

片段的形状（与既有字典同构）
---------------------------
字典是 **按域分组的两层结构**，``app.js`` 的 ``t("card.field.cost")`` 走的是
"点分路径查找"：``dict.card["field.cost"]``。所以片段里也按域分组、写**域名之后的后缀**::

    {
      "secretariat": {
        "title": "总裁办",
        "panel.identity": "身份确权"
      }
    }

对应的查找键是 ``secretariat.title`` / ``secretariat.panel.identity``。

校验口径（任一条不过即退出码 1，绝不"先合了再说"）
--------------------------------------------------
1. 后缀必须是低点分小写（``panel.identity``），域名与后缀拼起来才是完整 key；
2. zh 与 en 的 (域, 后缀) 集合必须完全一致（缺一条就是切语言后少一句话）；
3. en 值里不允许出现汉字（K-10：英文界面零中文残留）；两侧都不允许空值；
4. 占位参数（``{name}``）两侧必须一致；
5. 与既有字典冲突**且值不同**时报错（同一个 key 两套文案 = 谁被覆盖全看运气）；
6. 两个片段文件定义同一 (域, 后缀) 且值不同 → 报错；
7. ``embed.js`` 重新生成后与两份字典逐字节自洽（``--check`` 复核）。

运行：
    python tools/i18n_merge.py            # 合并 + 重生成 embed.js + 刷新 keys.md 统计
    python tools/i18n_merge.py --check    # 只校验是否已经合并（CI / 测试用）
    python tools/i18n_merge.py --json out.json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
I18N = ROOT / "agent_explainer" / "web" / "i18n"
PARTS = I18N / "parts"
ZH_PATH = I18N / "zh.json"
EN_PATH = I18N / "en.json"
EMBED_PATH = I18N / "embed.js"
KEYS_PATH = I18N / "keys.md"

CJK = re.compile(r"[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uac00-\ud7af\uf900-\ufaff]")
PARAM_RE = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")
PLACEHOLDER_RE = re.compile(r"\b(TODO|TBD|FIXME|XXX)\b", re.I)
SUFFIX_RE = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$")

EMBED_HEADER = """/*
 * Generated by web/selfcheck.mjs --sync-embed from i18n/zh.json + i18n/en.json.
 * Do not edit by hand. It exists so that index.html works straight from the
 * filesystem (file:// blocks fetch); when served over http(s), app.js re-reads
 * the canonical JSON dictionaries. web/selfcheck.mjs fails on any drift.
 */
"""


class MergeError(Exception):
    def __init__(self, code: str, reason: str, *, detail: dict[str, Any] | None = None) -> None:
        super().__init__(reason)
        self.code = code
        self.reason = reason
        self.detail = detail or {}


def _read_json(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}


def _part_files(lang: str) -> list[Path]:
    if not PARTS.is_dir():
        return []
    return sorted(PARTS.glob(f"*.{lang}.json"))


def _pairs(table: dict[str, Any], *, source: str) -> dict[str, tuple[str, str]]:
    """``{完整 key: (值, 来源)}``；键形状不合法直接报错。"""
    out: dict[str, tuple[str, str]] = {}
    for domain, entries in table.items():
        if not isinstance(entries, dict):
            raise MergeError("I18N_DOMAIN_NOT_OBJECT", f"域 {domain!r} 不是对象（{source}）")
        for suffix, value in entries.items():
            if not isinstance(value, str):
                raise MergeError("I18N_VALUE_NOT_STRING",
                                 f"{domain}.{suffix} 的值不是字符串（{source}）")
            full = f"{domain}.{suffix}"
            out[full] = (value, source)
    return out


def _check_pair(key: str, zh: str, en: str, problems: list[dict[str, Any]],
                *, strict_suffix: bool = False) -> None:
    if strict_suffix:
        suffix = key.split(".", 1)[1] if "." in key else ""
        if not SUFFIX_RE.match(suffix):
            problems.append({"code": "I18N_SUFFIX_INVALID", "key": key, "suffix": suffix})
    if not zh.strip() or not en.strip():
        problems.append({"code": "I18N_VALUE_EMPTY", "key": key})
    if CJK.search(en):
        problems.append({"code": "I18N_EN_HAS_CJK", "key": key, "value": en})
    if PLACEHOLDER_RE.search(zh) or PLACEHOLDER_RE.search(en):
        problems.append({"code": "I18N_PLACEHOLDER_VALUE", "key": key})
    if set(PARAM_RE.findall(zh)) != set(PARAM_RE.findall(en)):
        problems.append({"code": "I18N_PARAM_MISMATCH", "key": key,
                         "zh": sorted(set(PARAM_RE.findall(zh))),
                         "en": sorted(set(PARAM_RE.findall(en)))})


def collect() -> dict[str, Any]:
    """读片段 + 既有字典，返回合并后的两份表与问题清单。"""
    zh = _read_json(ZH_PATH)
    en = _read_json(EN_PATH)
    problems: list[dict[str, Any]] = []
    fragments: dict[str, dict[str, tuple[str, str]]] = {"zh": {}, "en": {}}

    for lang in ("zh", "en"):
        for path in _part_files(lang):
            table = _read_json(path)
            for key, pair in _pairs(table, source=path.name).items():
                if key in fragments[lang] and fragments[lang][key][0] != pair[0]:
                    problems.append({"code": "I18N_FRAGMENT_CONFLICT", "key": key,
                                      "lang": lang, "files": [fragments[lang][key][1], path.name]})
                fragments[lang][key] = pair

    zh_pairs = _pairs(zh, source="zh.json")
    en_pairs = _pairs(en, source="en.json")
    frag_zh = fragments["zh"]
    frag_en = fragments["en"]

    for key in sorted(set(frag_zh) - set(frag_en)):
        problems.append({"code": "I18N_FRAGMENT_MISSING_EN", "key": key})
    for key in sorted(set(frag_en) - set(frag_zh)):
        problems.append({"code": "I18N_FRAGMENT_MISSING_ZH", "key": key})
    for key in sorted(set(frag_zh) & set(frag_en)):
        _check_pair(key, frag_zh[key][0], frag_en[key][0], problems, strict_suffix=True)
    for key in sorted(set(zh_pairs) & set(en_pairs)):
        _check_pair(key, zh_pairs[key][0], en_pairs[key][0], problems)
    for key in sorted(set(zh_pairs) ^ set(en_pairs)):
        problems.append({"code": "I18N_DICT_ASYMMETRIC", "key": key,
                         "in_zh": key in zh_pairs, "in_en": key in en_pairs})

    for key in sorted(set(frag_zh) & set(frag_en)):
        if key in zh_pairs and zh_pairs[key][0] != frag_zh[key][0]:
            problems.append({"code": "I18N_CONFLICT", "key": key, "lang": "zh",
                             "existing": zh_pairs[key][0], "fragment": frag_zh[key][0]})
        if key in en_pairs and en_pairs[key][0] != frag_en[key][0]:
            problems.append({"code": "I18N_CONFLICT", "key": key, "lang": "en",
                             "existing": en_pairs[key][0], "fragment": frag_en[key][0]})

    merged_zh = json.loads(json.dumps(zh))
    merged_en = json.loads(json.dumps(en))
    added = 0
    for merged, source in ((merged_zh, frag_zh), (merged_en, frag_en)):
        for full_key, (value, _file) in source.items():
            domain, _, suffix = full_key.partition(".")
            bucket = merged.get(domain)
            if not isinstance(bucket, dict):
                bucket = {}
                merged[domain] = bucket
            if suffix not in bucket:
                added += 1
            bucket[suffix] = value

    return {
        "zh": merged_zh, "en": merged_en,
        "problems": problems,
        "added": added,
        "counts": {"zh": sum(len(v) for v in merged_zh.values()),
                   "en": sum(len(v) for v in merged_en.values())},
        "parts": [p.name for p in _part_files("zh")],
    }


def embed_text(zh: dict[str, Any], en: dict[str, Any]) -> str:
    """按 embed.js 现有格式逐字节重建。

    实况是 ``zh: {`` 里那个 ``{`` 就是 JSON 自己的开头括号，所以前缀写
    ``"    zh: "`` 而不是 ``"    zh: {\\n"`` —— 差一个括号 selfcheck 就会报漂移。
    """
    body = json.dumps(zh, ensure_ascii=False, indent=2)
    body_en = json.dumps(en, ensure_ascii=False, indent=2)
    return (EMBED_HEADER
            + "(function (global) {\n  'use strict';\n  global.TraceLensDicts = {\n"
            + "    zh: " + body + ",\n    en: " + body_en + "\n  };\n"
            + "}(typeof window !== 'undefined' ? window : "
              "(typeof globalThis !== 'undefined' ? globalThis : this)));\n")


def keys_md_text(zh: dict[str, Any], en: dict[str, Any], existing: str,
                 owned_domains: list[str]) -> str:
    """刷新 keys.md 的总数行，并为 5.0 的新域追加一节（既有章节保持原样）。"""
    total = sum(len(v) for v in zh.values())
    total_en = sum(len(v) for v in en.values())
    lines: list[str] = []
    for raw in existing.splitlines():
        if raw.startswith("**Key 总数"):
            lines.append(f"**Key 总数：{total}（zh {total} / en {total_en}，双向一致）**")
            continue
        if raw.startswith("## `") and "5.0" in existing:
            break
        lines.append(raw)
    lines.append("")
    lines.append("## 5.0 新增域（`tools/i18n_merge.py` 维护）")
    lines.append("")
    lines.append("> 这些域由 `web/i18n/parts/*.json` 片段合并而来：`tools/i18n_merge.py` 负责")
    lines.append("> 合并、校验（双语 key 一致、英文零中文、占位参数一致）并重生成 `embed.js`。")
    lines.append("")
    for domain in owned_domains:
        entries = zh.get(domain)
        if not isinstance(entries, dict) or not entries:
            continue
        lines.append(f"### `{domain}`（{len(entries)} 个）")
        lines.append("")
        lines.append("| key | zh | en |")
        lines.append("| --- | --- | --- |")
        for suffix in sorted(entries):
            key = f"{domain}.{suffix}"
            lines.append(f"| `{key}` | {entries[suffix]} | {en.get(domain, {}).get(suffix, '')} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="合并 5.0 i18n 片段并重生成 embed.js")
    parser.add_argument("--check", action="store_true", help="只校验，不写文件")
    parser.add_argument("--json", dest="json_path", default="", help="另存机器可读报告")
    args = parser.parse_args(argv)

    try:
        result = collect()
    except MergeError as exc:
        print(f"[FAIL] {exc.code}: {exc.reason}", file=sys.stderr)
        return 1

    problems = list(result["problems"])
    payload = {
        "ok": not problems,
        "added": result["added"],
        "counts": result["counts"],
        "parts": result["parts"],
        "problems": problems,
    }

    embed = embed_text(result["zh"], result["en"])
    if not args.check:
        ZH_PATH.write_text(json.dumps(result["zh"], ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
        EN_PATH.write_text(json.dumps(result["en"], ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
        EMBED_PATH.write_text(embed, encoding="utf-8")
    else:
        drift: list[str] = []
        current = EMBED_PATH.read_text(encoding="utf-8") if EMBED_PATH.exists() else ""
        if current != embed:
            drift.append("embed.js")
        if _read_json(ZH_PATH) != result["zh"]:
            drift.append("zh.json")
        if _read_json(EN_PATH) != result["en"]:
            drift.append("en.json")
        if drift:
            problems.append({"code": "I18N_NOT_MERGED", "files": drift})
            payload["problems"] = problems
            payload["ok"] = False

    if args.json_path:
        Path(args.json_path).write_text(json.dumps(payload, ensure_ascii=False, indent=2),
                                        encoding="utf-8")

    print(f"parts: {', '.join(result['parts']) or '(none)'}")
    print(f"keys: zh={result['counts']['zh']} en={result['counts']['en']} added={result['added']}")
    if problems:
        print(f"[FAIL] {len(problems)} 个问题：")
        for problem in problems[:40]:
            print("  - " + json.dumps(problem, ensure_ascii=False))
        return 1
    print("[PASS] 已合并，无漂移" if args.check else "[PASS] 双语字典一致，embed.js 已同步")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
